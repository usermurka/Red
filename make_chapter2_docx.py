FONT_NAME = "Times New Roman"
FONT_SIZE = Pt(14)
FOOTER_SIZE = Pt(12)


def set_run_font(run, size=FONT_SIZE, bold=False, italic=False):
    """Применить Times New Roman к латинице и кириллице (w:rFonts)."""
    run.font.name = FONT_NAME
    run.font.size = size
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = RGBColor(0, 0, 0)
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn('w:rFonts'))
    if rfonts is None:
        rfonts = OxmlElement('w:rFonts')
        rpr.append(rfonts)
    for attr in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
        rfonts.set(qn(attr), FONT_NAME)


def style_paragraph(p, first_line_cm=1.25, before=0, after=0,
                    line_spacing=1.5, align=WD_ALIGN_PARAGRAPH.JUSTIFY):
    """Единый стиль абзаца по Положению."""
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = line_spacing
    if first_line_cm is not None:
        pf.first_line_indent = Cm(first_line_cm)
    p.alignment = align
    return p


def add_body_paragraph(doc, text):
    """Основной абзац: TNR 14, 1,5 интервала, красная строка 1,25 см."""
    p = doc.add_paragraph()
    style_paragraph(p)
    set_run_font(p.add_run(text))
    return p


def _add_list_paragraph(doc, text, symbol=None, number=None):
    """Абзац списка с ручным маркером (символ или номер), без таблиц стилей."""
    p = doc.add_paragraph()
    style_paragraph(p, first_line_cm=1.25)
    marker = f"{number} " if number is not None else f"{symbol} "
    set_run_font(p.add_run(marker))
    set_run_font(p.add_run(text))
    return p


def add_bullet(doc, text):
    return _add_list_paragraph(doc, text, symbol="—")


def add_numbered(doc, idx, text):
    return _add_list_paragraph(doc, text, number=f"{idx}.")


def add_center_line(doc, text, bold=False, size=FONT_SIZE):
    p = doc.add_paragraph()
    style_paragraph(p, first_line_cm=0, align=WD_ALIGN_PARAGRAPH.CENTER)
    set_run_font(p.add_run(text), size=size, bold=bold)
    return p


def add_right_line(doc, text, bold=False):
    p = doc.add_paragraph()
    style_paragraph(p, first_line_cm=0, align=WD_ALIGN_PARAGRAPH.RIGHT)
    set_run_font(p.add_run(text), bold=bold)
    return p


def set_page_margins(section):
    """Поля по Положению: верх 2 см, низ 1,5 см, лево 3 см, право 2 см."""
    section.page_width = Cm(21.0)      # А4
    section.page_height = Cm(29.7)
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(1.5)
    section.left_margin = Cm(3)
    section.right_margin = Cm(2)
    section.footer_distance = Cm(1.0)


def clear_footer(section):
    """Очистить нижний колонтитул (для титульной секции)."""
    footer = section.footer
    footer.is_linked_to_previous = False
    for p in list(footer.paragraphs):
        p.text = ""


def add_page_number_footer(section):
    """Нижний колонтитул: номер страницы по центру, арабские цифры."""
    footer = section.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0]
    p.text = ""
    style_paragraph(p, first_line_cm=0, align=WD_ALIGN_PARAGRAPH.CENTER)
    run = p.add_run()
    set_run_font(run, size=FOOTER_SIZE)
    fld_begin = OxmlElement('w:fldChar')
    fld_begin.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText')
    instr.set(qn('xml:space'), 'preserve')
    instr.text = ' PAGE '
    fld_end = OxmlElement('w:fldChar')
    fld_end.set(qn('w:fldCharType'), 'end')
    run._element.append(fld_begin)
    run._element.append(instr)
    run._element.append(fld_end)


def set_pgnum_start(section, start="1"):
    """Начать нумерацию этой секции с единицы (w:pgNumType start)."""
    sectpr = section._sectPr
    pgnum = sectpr.find(qn('w:pgNumType'))
    if pgnum is None:
        pgnum = OxmlElement('w:pgNumType')
        sectpr.append(pgnum)
    pgnum.set(qn('w:start'), start)


def _force_fonts(style, size=FONT_SIZE, bold=False, caps=False):
    """Принудительно прописать шрифты стиля, включая кириллицу."""
    style.font.name = FONT_NAME
    style.font.size = size
    style.font.bold = bold
    style.font.color.rgb = RGBColor(0, 0, 0)
    if caps:
        style.font.all_caps = True
    rpr = style.element.get_or_add_rPr()
    rfonts = rpr.find(qn('w:rFonts'))
    if rfonts is None:
        rfonts = OxmlElement('w:rFonts')
        rpr.append(rfonts)
    for attr in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
        rfonts.set(qn(attr), FONT_NAME)


def setup_heading_styles(doc):
    """Heading 1 — ПРОПИСНЫМИ по центру; Heading 2 — полужирный по центру."""
    h1 = doc.styles['Heading 1']
    _force_fonts(h1, bold=True, caps=True)
    pf = h1.paragraph_format
    pf.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pf.first_line_indent = Cm(0)
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.5
    pf.keep_with_next = True

    h2 = doc.styles['Heading 2']
    _force_fonts(h2, bold=True)
    pf = h2.paragraph_format
    pf.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pf.first_line_indent = Cm(0)
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.5
    pf.keep_with_next = True


def add_h1(doc, text, page_break=False):
    if page_break:
        doc.add_page_break()
    h = doc.add_heading(text, level=1)
    for run in h.runs:
        set_run_font(run, bold=True)
    return h


def add_h2(doc, text, page_break=True):
    if page_break:
        doc.add_page_break()
    h = doc.add_heading(text, level=2)
    for run in h.runs:
        set_run_font(run, bold=True)
    return h


