def build_toc(doc):
    """Поле автособираемого оглавления TOC \\o \"1-2\" \\h \\z \\u."""
    add_center_line(doc, "СОДЕРЖАНИЕ", bold=True)
    p = doc.add_paragraph()
    style_paragraph(p, first_line_cm=0, align=WD_ALIGN_PARAGRAPH.LEFT)
    run = p.add_run()
    set_run_font(run)
    fld_begin = OxmlElement('w:fldChar')
    fld_begin.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText')
    instr.set(qn('xml:space'), 'preserve')
    instr.text = ' TOC \\o "1-2" \\h \\z \\u '
    fld_sep = OxmlElement('w:fldChar')
    fld_sep.set(qn('w:fldCharType'), 'separate')
    stub = OxmlElement('w:t')
    stub.text = "Оглавление пусто — обновите поле в Word (Ctrl+A, затем F9)."
    fld_end = OxmlElement('w:fldChar')
    fld_end.set(qn('w:fldCharType'), 'end')
    run._element.append(fld_begin)
    run._element.append(instr)
    run._element.append(fld_sep)
    run._element.append(stub)
    run._element.append(fld_end)


def _set_cell_border(cell):
    """Одинарная рамка вокруг ячейки (используется и для рамки рисунка)."""
    tcpr = cell._tc.get_or_add_tcPr()
    borders = OxmlElement('w:tcBorders')
    for edge in ('top', 'left', 'bottom', 'right'):
        el = OxmlElement('w:' + edge)
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), '6')
        el.set(qn('w:color'), '000000')
        borders.append(el)
    tcpr.append(borders)


def add_table(doc, caption, rows):
    """Таблица: подпись сверху, TNR 12, автоширина, границы."""
    cap = doc.add_paragraph()
    style_paragraph(cap, first_line_cm=0, align=WD_ALIGN_PARAGRAPH.LEFT)
    set_run_font(cap.add_run(caption), bold=True)
    table = doc.add_table(rows=len(rows), cols=len(rows[0]))
    table.style = 'Table Grid'
    for i, row in enumerate(rows):
        for j, value in enumerate(row):
            cell = table.cell(i, j)
            cell.text = ""
            p = cell.paragraphs[0]
            style_paragraph(p, first_line_cm=0, line_spacing=1.0,
                            align=WD_ALIGN_PARAGRAPH.LEFT)
            set_run_font(p.add_run(value), size=Pt(12), bold=(i == 0))
    after = doc.add_paragraph()
    style_paragraph(after, first_line_cm=0)
    return table


def add_figure_placeholder(doc, num):
    """Заглушка скриншота: рамка под картинку + подпись «Рисунок N.»."""
    box = doc.add_table(rows=1, cols=1)
    cell = box.cell(0, 0)
    _set_cell_border(cell)
    cell.text = ""
    p = cell.paragraphs[0]
    style_paragraph(p, first_line_cm=0, line_spacing=1.0,
                    align=WD_ALIGN_PARAGRAPH.CENTER)
    p.add_run("\n\n")
    hint = p.add_run("[ сюда вставьте скриншот ]")
    set_run_font(hint, size=Pt(12), italic=True)
    p.add_run("\n\n")
    box.height = Cm(6)
    cap = doc.add_paragraph()
    style_paragraph(cap, first_line_cm=0, align=WD_ALIGN_PARAGRAPH.CENTER)
    set_run_font(cap.add_run("Рисунок %d. %s" % (num, FIGURES[num])),
                 size=Pt(12))


def add_code_block(doc, lines):
    """Схема проекта: моноширинный блок без красной строки."""
    for line in lines:
        p = doc.add_paragraph()
        style_paragraph(p, first_line_cm=0, line_spacing=1.0,
                        align=WD_ALIGN_PARAGRAPH.LEFT)
        run = p.add_run(line)
        run.font.name = "Consolas"
        run.font.size = Pt(11)
        rpr = run._element.get_or_add_rPr()
        rfonts = rpr.find(qn('w:rFonts'))
        if rfonts is None:
            rfonts = OxmlElement('w:rFonts')
            rpr.append(rfonts)
        for attr in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
            rfonts.set(qn(attr), "Consolas")


def render_blocks(doc, blocks):
    """Отрисовка блоков подраздела по тегам."""
    for kind, payload in [(b[0], b[1:]) for b in blocks]:
        if kind == 'p':
            add_body_paragraph(doc, payload[0])
        elif kind == 'ul':
            for item in payload[0]:
                add_bullet(doc, item)
        elif kind == 'numbered':
            for i, item in enumerate(payload[0], start=1):
                add_numbered(doc, i, item)
        elif kind == 'table':
            add_table(doc, payload[0], payload[1])
        elif kind == 'fig':
            add_figure_placeholder(doc, payload[0])
        elif kind == 'code':
            add_code_block(doc, payload[0])


def build_chapter_2(doc):
    add_h1(doc, CHAPTER_HEADING, page_break=False)
    for text in INTRO_TEXTS:
        add_body_paragraph(doc, text)
    for title, blocks in SECTIONS:
        add_h2(doc, title, page_break=True)
        render_blocks(doc, blocks)


